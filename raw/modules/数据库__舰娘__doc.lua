这里保存的是所有的舰娘属性数据，均由特殊脚本自动生成，确保与游戏内一致。不能自动生成、需要手工录入的数据则存放在[[模块:特殊数据/舰娘]]中。如非特殊情况请勿更改此页面，若需要帮助或提交问题，请在[[讨论:留言讨论页]]中留言联系管理员。

各个参数之含义：

*number index&emsp;舰娘编号
*number rarity&emsp;稀有度、星级
*string type&emsp;舰种=(
::CV&emsp;航空母舰|
::CVL&emsp;轻型航母|
::AV&emsp;装甲航母|
::BB&emsp;战列舰|
::BBV&emsp;航空战列舰|
::BC&emsp;战列巡洋舰|
::CA&emsp;重巡洋舰|
::CAV&emsp;航空巡洋舰|
::CLT&emsp;重雷装巡洋舰|
::CL&emsp;轻巡洋舰|
::BM&emsp;浅水重炮舰|
::DD&emsp;驱逐舰|
::SSV&emsp;潜水航母|
::SS&emsp;潜水艇|
::SC&emsp;重炮潜水艇|
::AP&emsp;补给舰|
::DDG&emsp;导弹驱逐舰|
::DDGAA&emsp;防空导弹驱逐舰)
*string country&emsp;国籍=(
::日本|
::德国|
::英国|
::美国|
::意大利|
::法国|
::苏联|
::中国|
::???)
*string class&emsp;战舰番号
*string skill&emsp;技能名称
*number hp&emsp;耐久
*number atk&emsp;初始火力
*number tpd&emsp;初始鱼雷
*number def&emsp;初始装甲
*number aa&emsp;初始防空
*number eva&emsp;初始回避
*number acc&emsp;初始命中
*number as&emsp;初始对潜
*number rec&emsp;初始索敌
*number speed&emsp;航速
*number luck&emsp;幸运
*string range=(&emsp;射程
::无|
::短|
::中|
::长|
::超长)
*string size=(&emsp;舰型补正
::小型舰|
::中型舰|
::大型舰)
*number atkMax&emsp;最大火力
*number tpdMax&emsp;最大鱼雷
*number defMax&emsp;最大装甲
*number aaMax&emsp;最大对潜
*number evaMax&emsp;最大回避
*number accMax&emsp;最大命中
*number asMax&emsp;最大对潜
*number recMax&emsp;最大索敌
*number cap1&emsp;第1格飞机搭载量
*number cap2&emsp;第2格飞机搭载量
*number cap3&emsp;第3格飞机搭载量
*number cap4&emsp;第4格飞机搭载量
*number msl1&emsp;第1格导弹搭载量
*number msl2&emsp;第2格导弹搭载量
*number msl3&emsp;第3格导弹搭载量
*number msl4&emsp;第4格导弹搭载量
*string eq1&emsp;第1格初始装备
*string eq2&emsp;第2格初始装备
*string eq3&emsp;第3格初始装备
*string eq4&emsp;第4格初始装备
*number sFuel&emsp;出击燃料消耗
*number sAmmo&emsp;出击弹药消耗
*number rFuel&emsp;每修复1点耐久燃料消耗
*number rSteel&emsp;每修复1点耐久钢材消耗
*number rTime&emsp;修理时间系数
*number sAtk&emsp;作为强化素材提供的火力经验
*number sTpd&emsp;作为强化素材提供的鱼雷经验
*number sDef&emsp;作为强化素材提供的装甲经验
*number sAa&emsp;作为强化素材提供的对空经验
*number dFuel&emsp;拆解所回收的燃料
*number dAmmo&emsp;拆解所回收的弹药
*number dSteel&emsp;拆解所回收的钢材
*number dBaux&emsp;拆解所回收的铝材
*mod&emsp;改造后的战舰名
*number modLV&emsp;改造等级
*string coreType=(&emsp;改造所需核心类型
::驱逐|
::巡洋|
::战列|
::航母|
::潜艇)
*number coreNum&emsp;改造所需核心数量
*number mFuel&emsp;改造所需燃料
*number mAmmo&emsp;改造所需弹药
*number mSteel&emsp;改造所需钢材
*number mBaux&emsp;改造所需铝材